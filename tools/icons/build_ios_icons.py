"""Generate small LVGL alpha caches from the supplied SVG source assets."""
import argparse
import hashlib
import io
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "framework/ui/ios_icon_assets.c"
ICONS = (("ios-wifi.svg", 26, "hachimi_ios_wifi_26"),
         ("ios-wifi.svg", 44, "hachimi_ios_wifi_44"),
         ("ios-battery-full.svg", 36, "hachimi_ios_battery_36"),
         ("ios-battery-charging.svg", 36, "hachimi_ios_battery_charging_36"),
         ("ios-musical-notes.svg", 40, "hachimi_ios_musical_notes_40"),
         ("ios-sunny.svg", 40, "hachimi_ios_sunny_40"),
         ("yitaiwang.svg", 44, "hachimi_ethernet_44"))


def generate():
    import resvg_py
    from PIL import Image
    lines = ['/* Generated by tools/icons/build_ios_icons.py. Edit the SVG sources, not this file. */',
             '#include "ios_icon_assets.h"', '']
    for filename, size, name in ICONS:
        source = ROOT / "custom/assets/ios" / filename
        original = source.read_bytes()
        png = resvg_py.svg_to_bytes(svg_string=original.decode("utf-8"), width=size * 4,
                                   height=size * 4, skip_system_fonts=True)
        alpha = Image.open(io.BytesIO(png)).convert("RGBA").getchannel("A")
        alpha = alpha.resize((size, size), Image.Resampling.LANCZOS)
        stride = (size + 3) & ~3
        pixels = bytearray(stride * size)
        raw = alpha.tobytes()
        for y in range(size):
            pixels[y * stride:y * stride + size] = raw[y * size:(y + 1) * size]
        lines += [f'/* Source: custom/assets/ios/{filename}; SHA-256: {hashlib.sha256(original).hexdigest()} */',
                  f'static const uint8_t {name}_data[] LV_ATTRIBUTE_MEM_ALIGN = {{']
        for i in range(0, len(pixels), 16):
            lines.append('    ' + ', '.join(f'0x{value:02x}' for value in pixels[i:i + 16]) + ',')
        lines += ['};', f'const lv_image_dsc_t {name} = {{',
                  '    .header = {.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8,',
                  f'               .w = {size}, .h = {size}, .stride = {stride}}},',
                  f'    .data_size = sizeof({name}_data), .data = {name}_data', '};', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--deps", type=Path, help="Optional isolated Python dependency directory")
    parser.add_argument("--check", action="store_true", help="Check the committed cache without writing")
    args = parser.parse_args()
    if args.deps:
        sys.path.insert(0, str(args.deps.resolve()))
    generated = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != generated:
            raise SystemExit("SVG icon cache is stale; regenerate ios_icon_assets.c")
        print(f"PASS SVG sources match all {len(ICONS)} native-size alpha caches")
    else:
        OUTPUT.write_text(generated, encoding="utf-8", newline="\n")
        print(f"Generated {len(ICONS)} native-size alpha caches from the supplied SVGs")


if __name__ == "__main__":
    main()
